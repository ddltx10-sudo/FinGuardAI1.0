# AI QUESTION
# =========================================================

def ask_ai(text: str) -> str:

    text = text.strip()

    if not text:
        return "⚠️ Напишите финансовый вопрос."

    # -----------------------------------------------------
    # FINANCE FILTER
    # -----------------------------------------------------

    if not is_finance_question(text):

        return (
            "⚠️ FinGuard AI предназначен только для "
            "анализа финансовых рынков и финансовых вопросов."
        )

    # -----------------------------------------------------
    # NORMAL AI
    # -----------------------------------------------------

    prompt = f"""
Пользователь задал финансовый вопрос:

{text}

Ответь на русском языке.

Если вопрос требует расчёта, покажи формулу и результат.

Если вопрос касается финансового риска, объясни риски.

Если данных недостаточно, прямо скажи об этом.
"""

